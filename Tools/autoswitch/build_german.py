#!/usr/bin/env python3
"""Builds Engine/GermanData.h: German words (ASCII as typed) with frequency scores, for German-aware auto switch.
Source: de_50k.txt, FrequencyWords by Hermit Dave (OpenSubtitles 2018), content CC BY-SA 4.0.

A German word typed in Vietnamese mode is put back as typed, like an English word ("wir" not "ửi", "der" not "dẻ").
Words with ä ö ü ß never reach Telex (the app ends the word at such a letter); their ASCII spellings as typed
without umlauts (fuer, schoen, gruesse, strasse: Swiss German writes ss) are added here.
Score = round(10 * log10(occurrences per million)), the scale of AutoSwitchData.h.
"""
import math, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'Engine', 'GermanData.h')
MAX_WORDS = int(os.environ.get('VIKEY_DE_WORDS', '30000'))
MIN_SCORE = int(os.environ.get('VIKEY_DE_MIN', '-15'))
rows = []
for line in open(os.path.join(HERE, 'de_50k.txt'), encoding='utf-8'):
    p = line.split()
    if len(p) == 2: rows.append((p[0].lower(), int(p[1])))
total = sum(c for _, c in rows)
def score(c): return max(-120, min(120, round(10 * math.log10(c * 1e6 / total))))
TR = str.maketrans({'ä': 'ae', 'ö': 'oe', 'ü': 'ue', 'ß': 'ss'})
de = {}
for w, c in rows[:MAX_WORDS]:
    a = w.translate(TR)
    if not re.fullmatch('[a-z]{2,}', a): continue
    s = score(c)
    if s < MIN_SCORE: continue
    de[a] = max(de.get(a, -999), s)
# Subtitle names and filler that are common Vietnamese in Telex: never German
for w in ('anh', 'em', 'ong', 'ba', 'co', 'toi', 'nhe', 'nha', 'vay', 'thi', 'la', 'ma', 'ok', 'oki'):
    de.pop(w, None)
# MiKey extra words (mikey_extra.txt): always English, any language setting, top score like en_extra.txt
extra = {}
for line in open(os.path.join(HERE, 'mikey_extra.txt'), encoding='utf-8'):
    if line.startswith('#'): continue
    for w in line.split(): extra[w.lower()] = 40

def emit(f, name, d):
    keys = sorted(d)
    offs, pos = [], 0
    for k in keys: offs.append(pos); pos += len(k) + 1
    f.write(f'static const char {name}Words[] =\n')
    for i in range(0, len(keys), 200):
        f.write('    "' + ''.join(k + '\\0' for k in keys[i:i + 200]) + '"\n')
    f.write(';\n')
    f.write(f'static const unsigned int {name}Offsets[{len(keys)}] = {{' + ','.join(map(str, offs)) + '};\n')
    f.write(f'static const signed char {name}Scores[{len(keys)}] = {{' + ','.join(str(d[k]) for k in keys) + '};\n')
    f.write(f'static const int {name}Count = {len(keys)};\n\n')

with open(OUT, 'w') as f:
    f.write('// Generated by Tools/autoswitch/build_german.py. Do not edit.\n')
    f.write('// Word frequencies: FrequencyWords (Hermit Dave), OpenSubtitles 2018, CC BY-SA 4.0.\n')
    f.write('#ifndef GermanData_h\n#define GermanData_h\n\n')
    emit(f, 'kAutoSwitchDe', de)
    emit(f, 'kAutoSwitchMk', extra)
    f.write('#endif\n')
print('de', len(de), 'extra', len(extra), 'bytes', os.path.getsize(OUT))
for w in ('ich', 'wir', 'der', 'ist', 'dass', 'fuer', 'schoen', 'gruesse', 'strasse', 'nur', 'uns'):
    print(w, de.get(w))
